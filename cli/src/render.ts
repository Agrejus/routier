import type { EmittedFunction } from "@routier/core";

export const OUTPUT_FILE = "routier.generated.js";
const OUTPUT_TYPES_FILE = "routier.generated.d.ts";

export type OutputFile = {
    readonly name: string;
    readonly content: string;
};

const HEADER = "// Generated by routier generate. Do not edit.\n";

const renderFunction = ({ key, parameters, body }: EmittedFunction): string =>
    `${JSON.stringify(key)}: function(${parameters.join(", ")}) {\n${body}\n}`;

const renderFunctions = (functions: readonly EmittedFunction[]): string =>
    [...functions].sort((a, b) => a.key.localeCompare(b.key)).map(renderFunction).join(",\n");

export const renderOutput = (functions: readonly EmittedFunction[]): OutputFile[] => [
    {
        name: OUTPUT_FILE,
        content:
            `${HEADER}import { registerGeneratedFunctions } from "@routier/core";\n\n` +
            `registerGeneratedFunctions({\n${renderFunctions(functions)}\n});\n`,
    },
    { name: OUTPUT_TYPES_FILE, content: `${HEADER}export {};\n` },
];
