import { describe, expect, it } from '@jest/globals';
import { renderOutput } from './render';

const functions = [
    { key: '2', parameters: ['a', 'b'], body: 'return a === b;' },
    { key: '1', parameters: ['entity'], body: 'return entity;' },
];

const contentOf = (name: string) => renderOutput(functions).find(file => file.name === name)?.content ?? '';

describe('renderOutput', () => {
    it('writes one script and its types', () => {
        expect(renderOutput(functions).map(file => file.name)).toEqual(['routier.generated.js', 'routier.generated.d.ts']);
    });

    it('registers each function under its key, in key order', () => {
        expect(contentOf('routier.generated.js')).toContain(
            'registerGeneratedFunctions({\n"1": function(entity) {\nreturn entity;\n},\n"2": function(a, b) {\nreturn a === b;\n}\n});\n',
        );
    });

    it('imports the register function from core', () => {
        expect(contentOf('routier.generated.js')).toContain('import { registerGeneratedFunctions } from "@routier/core";\n\n');
    });

    it('produces functions that run', () => {
        const source = contentOf('routier.generated.js')
            .replace('import { registerGeneratedFunctions } from "@routier/core";', '')
            .replace('registerGeneratedFunctions(', 'return (');

        expect(new Function(source)()['2'](1, 1)).toBe(true);
    });

    it('types the script as a module with no exports', () => {
        expect(contentOf('routier.generated.d.ts')).toContain('export {};\n');
    });

    it('marks every file as generated', () => {
        for (const file of renderOutput(functions)) {
            expect(file.content.startsWith('// Generated by routier generate. Do not edit.\n')).toBe(true);
        }
    });
});
